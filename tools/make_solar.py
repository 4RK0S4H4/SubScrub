"""Regenerate subscrub/ui/solar.py: only the Solar icons SubScrub draws, from the @iconify-json/solar package.

    npm pack @iconify-json/solar@1.2.13 && tar xzf iconify-json-solar-1.2.13.tgz
    python tools/make_solar.py package/icons.json

Linear for small controls, bold duotone where the icon carries a screen (S4 Glass). Add a name to the lists below,
run the script again and commit solar.py.
"""
import json
import sys
from pathlib import Path

LINEAR = ["add-folder", "alt-arrow-down", "alt-arrow-left", "alt-arrow-right", "alt-arrow-up", "arrow-left",
          "arrow-right", "check-circle", "check-read", "clapperboard-play", "close", "copy", "danger-circle",
          "danger-triangle", "document-add", "document-text", "flag", "folder", "folder-open", "history",
          "info-circle", "keyboard", "magnifier", "menu-dots", "moon", "pen", "restart", "settings",
          "stop-circle", "subtitles", "sun", "undo-left", "upload-minimalistic"]
DUOTONE = ["check-circle", "clapperboard-play", "danger-triangle", "folder", "info-circle", "magic-stick-3",
           "pallete-2", "stars-minimalistic", "subtitles", "tag-horizontal", "upload-minimalistic",
           "videocamera-record"]


def main(path: str):
    icons = json.loads(Path(path).read_text(encoding="utf-8"))["icons"]
    out = ['"""Solar icons (480 Design, CC BY 4.0) via @iconify-json/solar 1.2.13: only the ones SubScrub draws.',
           "", "Linear for small controls, bold duotone for icons that carry a screen. Bodies use currentColor.",
           "Generated by tools/make_solar.py; edit the lists there, not this file.", '"""', "", "LINEAR = {"]
    out += [f"    {n!r}: {icons[n + '-linear']['body']!r}," for n in LINEAR]
    out += ["}", "", "DUOTONE = {"]
    out += [f"    {n!r}: {icons[n + '-bold-duotone']['body']!r}," for n in DUOTONE]
    out += ["}", ""]
    dest = Path(__file__).resolve().parent.parent / "subscrub" / "ui" / "solar.py"
    dest.write_text("\n".join(out), encoding="utf-8")
    print(f"Wrote {dest} ({len(LINEAR)} linear, {len(DUOTONE)} duotone)")


if __name__ == "__main__":
    main(sys.argv[1])
